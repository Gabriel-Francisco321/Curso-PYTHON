#
# O comando #

# Múltiplas atribuições em uma linha: a receberá 5 e b receberá 3 
a, b = 5, 3

# Adição
print (a + b)

# Subtração
print (a - b)

# Multiplicação
print (a * b)

# Divisão
print (a / b)

# Divisão inteira
print (a // b)

# Resto da divisão inteira
print (a % b)

# Potenciação
print (a ** b)

print ("\n")


#
# Operadores Relacionais 
# ============================================================== #

# Maior que (>) / Menor que (<)
print (a > b) # True

# Maior ou igual a (>=) / Menor ou igual a (<=)
print (a <= b) # False

# Igual (==)
print (a == b) # False

# Diferente (!=)
print (a != b) # True

print ("\n")

#
# Print
# O comando print nos permte não só exibir texto, mas também o conteúdo de variáveis
# ============================================================== #

# Os parametros sep e end representam respectivamente o carater de separação entre valores, e o caracter de encerramento.
print ("Olá", end= "!") # Alterou o caracter de encerramento de \n para !
